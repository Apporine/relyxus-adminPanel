const onboardingStages = new Set<LifecycleStage>([
  "commercial_handoff",
  "security_review",
  "architecture_discovery",
  "pilot_ready",
  "deployment_ready",
]);

function domainOf(legal: string): string {
  return `${legal
    .toLowerCase()
    .split(" ")[0]
    ?.replace(/[^a-z]/g, "")}.example`;
}

export const customers: Customer[] = seeds.map((seed, index) => ({
  id: seed.id,
  displayName: seed.name,
  legalName: seed.legal,
  status: onboardingStages.has(seed.stage) ? "onboarding" : "active",
  parentId: seed.parentId,
  segment: seed.segment,
  industry: seed.industry,
  headquartersCountry: seed.country,
  region: seed.region,
  website: `https://${domainOf(seed.legal)}`,
  lifecycleStage: seed.stage,
  customerSince: `${seed.since}T00:00:00Z`,
  goLiveAt: onboardingStages.has(seed.stage) ? undefined : `${seed.since}T00:00:00Z`,
  nextRenewalAt: seed.renewal ? `${seed.renewal}T23:59:59Z` : undefined,
  health: seed.health,
  annualContractValue:
    seed.acvK === undefined
      ? undefined
      : { amountMinor: seed.acvK * 100_000, currency: seed.currency },
  supportTier: seed.tier,
  owners: seed.owners,
  productIds: seed.products,
  deploymentModel:
    seed.products.includes("prd_sentinel") && seed.id === "cus_meridian"
      ? "apporine_managed"
      : "customer_hosted",
  dataResidency:
    seed.region === "UK"
      ? "United Kingdom"
      : seed.region === "EU"
        ? "European Union"
        : seed.country,
  lastActivityAt: seed.lastActivity,
  references: {
    crmId: `CRM-${String(1040 + index * 7).padStart(5, "0")}`,
    financeId: seed.acvK ? `FIN-${String(220 + index * 3).padStart(4, "0")}` : undefined,
    supportId: `SUP-${String(300 + index).padStart(4, "0")}`,
  },
}));

